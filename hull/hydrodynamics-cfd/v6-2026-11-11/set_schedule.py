"""Write the speed schedule into 0/U, constant/fvModels and speed-schedule.csv.

The whole domain is accelerated (fvModel `acceleration`, i.e. the frame of the accelerating
boat), and the inlet velocity and outlet water-phase mean velocity follow the same function.
Ramping only the inlet sent a long wave down the tank: water piled up upstream and the hull
rode up 0.44 m before the run diverged (first ramp attempt, 2026-11-12).

Schedule: 1 cm/s creep (outlet BC is 0/0 at exactly zero), hold to T0, half-cosine ramp to
U_MAX over T0..T1, hold to T_END.
"""
import math, pathlib, re

HERE = pathlib.Path(__file__).resolve().parent
U0, U_MAX = 0.01, 8.9408            # m/s; 8.9408 m/s = 20 mph
T0, T1, T_END = 1.0, 11.0, 16.0
DT_TABLE = 0.25


def speed(t):
    if t <= T0:
        return U0
    if t >= T1:
        return U_MAX
    return U0 + (U_MAX - U0) * 0.5 * (1 - math.cos(math.pi * (t - T0) / (T1 - T0)))


times = [0.0, T0] + [T0 + DT_TABLE * k for k in range(1, int(round((T1 - T0) / DT_TABLE)))] + [T1, T_END]
pts = [(t, speed(t)) for t in times]
vec = '\n'.join(f'            ({t:g} (-{u:.6f} 0 0))' for t, u in pts)
sca = '\n'.join(f'            ({t:g} {u:.6f})' for t, u in pts)

p = HERE / '0/U'
t = p.read_text()
t = re.sub(r'uniformValue    table\n\s*\(\n.*?\n\s*\);', f'uniformValue    table\n        (\n{vec}\n        );', t, flags=re.S)
t = re.sub(r'UnMean          table\n\s*\(\n.*?\n\s*\);', f'UnMean          table\n        (\n{sca}\n        );', t, flags=re.S)
t = re.sub(r'internalField   uniform \([^)]*\);', f'internalField   uniform (-{U0} 0 0);', t)
p.write_text(t)

(HERE / 'constant/fvModels').write_text(f"""FoamFile
{{
    format      ascii;
    class       dictionary;
    location    "constant";
    object      fvModels;
}}
// Generated by set_schedule.py

// Accelerating frame: the whole domain follows the boat's speed schedule.
frameAcceleration
{{
    type            acceleration;
    cellZone        all;
    U               U;
    velocity        table
    (
{vec}
    );
}}

// Absorb long waves near the outlet (last 4 m) and inlet (last 2 m).
outletDamping
{{
    type            verticalDamping;
    libs            ("libwaves.so");
    origin          (-8 0 0);
    direction       (-1 0 0);
    scale
    {{
        type        halfCosineRamp;
        start       0;
        duration    4;
    }}
    lambda          [0 0 -1 0 0 0 0] 1;
}}

inletDamping
{{
    type            verticalDamping;
    libs            ("libwaves.so");
    origin          (4 0 0);
    direction       (1 0 0);
    scale
    {{
        type        halfCosineRamp;
        start       0;
        duration    2;
    }}
    lambda          [0 0 -1 0 0 0 0] 1;
}}
""")

(HERE / 'speed-schedule.csv').write_text(
    'time_s,speed_m_s,speed_mph\n' + ''.join(f'{t:g},{u:.6f},{u / 0.44704:.3f}\n' for t, u in pts))

c = HERE / 'system/controlDict'
s = re.sub(r'endTime\s+[\d.]+;', f'endTime         {T_END:g};', c.read_text())
c.write_text(s)
print(f'{len(pts)} schedule points, end {T_END} s, max {U_MAX} m/s')
