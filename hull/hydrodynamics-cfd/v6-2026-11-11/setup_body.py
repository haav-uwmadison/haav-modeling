"""Rigid-body inputs for the v6 half-model planing run.

Reads the v6 component loading sheet (filled rows only, as in the 11/11 hydrostatics run),
converts CAD inches to the CFD frame, rotates by the static rest trim used for the mesh, and
writes half-model mass, CG and inertia to constant/bodyProperties (included by dynamicMeshDict).

CFD frame: x forward from transom, y = -CAD X (half domain y <= 0), z up from aft keel, metres.
Inertia: point masses for each component, plus the printed shell spread uniformly over the
exterior hull surface (thin-shell estimate, re-centred on the shell's supplied CG). Other
components' own inertias are omitted.
"""
import csv, json, math, pathlib, struct

HERE = pathlib.Path(__file__).resolve().parent
HYDRO = HERE.parents[1] / 'hydrostatics' / 'v6-2026-11-11'
IN, LB = 0.0254, 0.45359237
TRIM_DEG = 1.807          # static rest trim, bow up (NavalToolbox v6 run)
RIM_Z = 12 * IN

rows = [r for r in csv.DictReader(open(HYDRO / 'component-masses.csv')) if r['mass_lbs'].strip()]
comps = [dict(id=r['component_id'], m=float(r['mass_lbs']) * LB,
              p=(float(r['cg_y_in']) * IN, -float(r['cg_x_in']) * IN, float(r['cg_z_in']) * IN))
         for r in rows]
M = sum(c['m'] for c in comps)
cg = tuple(sum(c['m'] * c['p'][i] for c in comps) / M for i in range(3))

# Thin-shell own inertia of the printed shell from the exterior (uncapped) hull surface.
data = (HYDRO / 'geometry' / 'hull-envelope.stl').read_bytes()
n = struct.unpack_from('<I', data, 80)[0]
tris = []
for k in range(n):
    v = struct.unpack_from('<12f', data, 84 + 50 * k)[3:]
    a, b, c = v[0:3], v[3:6], v[6:9]
    if all(abs(p[2] - RIM_Z) < 1e-4 for p in (a, b, c)):
        continue  # artificial rim cap, not shell
    u = [b[i] - a[i] for i in range(3)]; w = [c[i] - a[i] for i in range(3)]
    cr = (u[1]*w[2]-u[2]*w[1], u[2]*w[0]-u[0]*w[2], u[0]*w[1]-u[1]*w[0])
    area = 0.5 * math.sqrt(sum(x * x for x in cr))
    tris.append((area, [(a[i] + b[i] + c[i]) / 3 for i in range(3)], (a, b, c)))
A = sum(t[0] for t in tris)
shell = next(c for c in comps if c['id'] == 'printed_shell')
sc = [sum(t[0] * t[1][i] for t in tris) / A for i in range(3)]

def tri_second_moments(t):
    # exact second moments of a uniform triangle about the shell centroid sc
    area, _, verts = t
    d = [[v[i] - sc[i] for i in range(3)] for v in verts]
    S = [[0.0] * 3 for _ in range(3)]
    for i in range(3):
        for j in range(3):
            s = sum(p[i] * p[j] for p in d)
            s +=(d[0][i]+d[1][i]+d[2][i]) * (d[0][j]+d[1][j]+d[2][j])
            S[i][j] = area * s / 12.0
    return S

S = [[0.0] * 3 for _ in range(3)]
for t in tris:
    St = tri_second_moments(t)
    for i in range(3):
        for j in range(3):
            S[i][j] += St[i][j]
rho_a = shell['m'] / A
Sm = [[rho_a * S[i][j] for j in range(3)] for i in range(3)]
I_shell_own = [[(Sm[0][0] + Sm[1][1] + Sm[2][2]) * (i == j) - Sm[i][j] for j in range(3)] for i in range(3)]

# Total inertia about the CG: point masses (parallel axis) + shell own inertia.
I = [[0.0] * 3 for _ in range(3)]
for c in comps:
    r = [c['p'][i] - cg[i] for i in range(3)]
    r2 = sum(x * x for x in r)
    for i in range(3):
        for j in range(3):
            I[i][j] += c['m'] * (r2 * (i == j) - r[i] * r[j])
for i in range(3):
    for j in range(3):
        I[i][j] += I_shell_own[i][j]

# Rotate CG into the mesh frame (hull rotated Ry = -TRIM about the transom keel).
th = math.radians(-TRIM_DEG)
cs, sn = math.cos(th), math.sin(th)
cg_mesh = (cg[0] * cs + cg[2] * sn, cg[1], -cg[0] * sn + cg[2] * cs)

half = dict(mass=M / 2, Ixx=I[0][0] / 2, Ixy=I[0][1] / 2, Ixz=I[0][2] / 2,
            Iyy=I[1][1] / 2, Iyz=I[1][2] / 2, Izz=I[2][2] / 2)
# Half model: drop transverse cross terms (the half body is mirrored, roll/yaw are locked).
half['Ixy'] = half['Iyz'] = 0.0

(HERE / 'constant' / 'bodyProperties').write_text(f"""// Generated by setup_body.py; do not edit by hand.
// Full boat {M/LB:.3f} lb = {M:.4f} kg; half model below.
bodyMass        {half['mass']:.6f};
bodyCentre      ({cg_mesh[0]:.6f} 0 {cg_mesh[2]:.6f});
bodyInertia     ({half['Ixx']:.6f} 0 {half['Ixz']:.6f} {half['Iyy']:.6f} 0 {half['Izz']:.6f});
bodyRotation    ({math.cos(math.radians(TRIM_DEG)):.10f} 0 {math.sin(math.radians(TRIM_DEG)):.10f}
                 0 1 0
                 {-math.sin(math.radians(TRIM_DEG)):.10f} 0 {math.cos(math.radians(TRIM_DEG)):.10f});
""")
report = dict(components=[c['id'] for c in comps], full_mass_lb=M / LB, full_mass_kg=M,
              cg_unrotated_m=cg, cg_unrotated_in=[x / IN for x in cg], cg_mesh_m=cg_mesh,
              full_inertia_about_cg_kg_m2=I, shell_own_inertia_kg_m2=I_shell_own,
              shell_surface_centroid_m=sc, shell_supplied_cg_m=shell['p'],
              half_model=half, trim_deg=TRIM_DEG)
(HERE / 'body-report.json').write_text(json.dumps(report, indent=2))
print(json.dumps(dict(full_mass_lb=round(M / LB, 3), cg_in=[round(x / IN, 4) for x in cg],
                      cg_mesh_m=[round(x, 5) for x in cg_mesh], half=half,
                      pitch_inertia_full=I[1][1], shell_own_Iyy=I_shell_own[1][1]), indent=1))
